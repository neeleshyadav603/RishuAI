"""Write app/assets/brain.json for the phone's own brain from config/ and shared/prompts.

Model IDs stay in config/models.yaml; this file is generated from it (a core
test checks that the committed copy is up to date).
Usage: python scripts/make_phone_brain.py [--check]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "app" / "assets" / "brain.json"


def build() -> str:
    models = yaml.safe_load((ROOT / "config" / "models.yaml").read_text(encoding="utf-8"))
    prompts = ROOT / "shared" / "prompts"
    providers = {}
    for name in models["order"]:
        cfg = models["providers"].get(name) or {}
        if cfg.get("local") or cfg.get("managed"):
            continue  # the phone has no local model: online providers only
        providers[name] = {
            "label": cfg.get("label") or name,
            "key_url": cfg.get("key_url") or "",
            "base_url": cfg["base_url"],
            "models": {role: list(ids or []) for role, ids in (cfg.get("models") or {}).items()},
        }
    brain = {
        "note": "Generated by scripts/make_phone_brain.py from config/models.yaml and shared/prompts. Do not edit.",
        "order": list(providers),
        "providers": providers,
        "speech": models.get("speech", {}),
        "prompts": {
            "persona": (prompts / "persona_rishu.md").read_text(encoding="utf-8").strip(),
            "personas": {p.stem: p.read_text(encoding="utf-8").strip() for p in sorted((prompts / "personas").glob("*.md"))},
            "rules": (prompts / "system_rules_phone.md").read_text(encoding="utf-8").strip(),
        },
    }
    return json.dumps(brain, ensure_ascii=False, indent=1) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
